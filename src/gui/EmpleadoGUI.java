    private void jtblRegistrosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtblRegistrosMouseClicked

        try {
            int id = (int) objDtm.getValueAt(jtblRegistros.getSelectedRow(), 0);

            try ( // Llamar a tu método DAO
                    ResultSet rsEmpl = objEmpleadoDAO.searchID(id)) {
                if (rsEmpl.next()) {
                    jtxtCodigo.setText(String.valueOf(rsEmpl.getInt(1)));
                    jtxtNombre.setText(rsEmpl.getString(2));
                    jtxtApPaterno.setText(rsEmpl.getString(3));
                    jtxtApMaterno.setText(rsEmpl.getString(4));

                    String sexo = rsEmpl.getString(5);
                    jrbtMasculino.setSelected("M".equalsIgnoreCase(sexo));
                    jrbtFemenino.setSelected("F".equalsIgnoreCase(sexo));

                    jtxtDireccion.setText(rsEmpl.getString(6));

                    jcmbDistrito.removeAllItems();
                    jcmbDistrito.addItem(rsEmpl.getString(7));

                    jtxtTelefono.setText(rsEmpl.getString(8));
                    jtxtCelular.setText(rsEmpl.getString(9));
                    jtxtEmail.setText(rsEmpl.getString(10));
                    jtxtObservacion.setText(rsEmpl.getString(11));

                    // --- Carga segura de la imagen ---
                    Blob fotoBlob = rsEmpl.getBlob(12);
                    if (fotoBlob != null && fotoBlob.length() > 0) {
                        System.out.println("Imgena existe");
                        byte[] data = fotoBlob.getBytes(1, (int) fotoBlob.length());
                        BufferedImage foto = ImageIO.read(new ByteArrayInputStream(data));

                        if (foto != null) {
                            System.out.println("Imagen contruida");
                            ImageIcon imagen = new ImageIcon(foto);
                            Icon icon = new ImageIcon(imagen.getImage().getScaledInstance(
                                    jlblFoto.getWidth(),
                                    jlblFoto.getHeight(),
                                    Image.SCALE_SMOOTH
                            ));
                            jlblFoto.setIcon(icon);
                        } else {
                            jlblFoto.setIcon(null);
                        }
                    } else {
                        jlblFoto.setIcon(null);
                        System.out.println("⚠️ No hay imagen almacenada para este registro.");
                    }
                }
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error al cargar empleado: " + e.getMessage());
        }


    }//GEN-LAST:event_jtblRegistrosMouseClicked

    private void jbtnSeleccionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnSeleccionarActionPerformed
        JFileChooser objJFileChooser = new JFileChooser();
        int op = objJFileChooser.showOpenDialog(this);
        
        if (op == objJFileChooser.APPROVE_OPTION) {
            ruta = objJFileChooser.getSelectedFile().getAbsolutePath();
            jlblFoto.setIcon(new ImageIcon(ruta));

            // Escalar la imagen al tamaño del JLabel
            ImageIcon iconoOriginal = new ImageIcon(ruta);
            Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(
                    jlblFoto.getWidth(),
                    jlblFoto.getHeight(),
                    Image.SCALE_SMOOTH
            );
            jlblFoto.setIcon(new ImageIcon(imagenEscalada));
            jtxtRuta.setText(ruta);
        }
    }//GEN-LAST:event_jbtnSeleccionarActionPerformed


