    private void limpiarJTable() {
        while (objDtm.getRowCount() > 0) {
            objDtm.removeRow(0);
        }
    }

    private void habilitarControles(boolean b) {
        jtxtNombre.setEditable(b);
        jtxtPrecio.setEditable(b);
        jtxtObservacion.setEditable(b);

        jbtnGrabar.setEnabled(b);
        jbtnCancelar.setEnabled(b);
        jbtnNuevo.setEnabled(!b);
        jbtnEditar.setEnabled(!b);
        jbtnBorrar.setEnabled(!b);
        jbtnSalir.setEnabled(!b);

        jtxtBuscar.setEditable(!b);
        jtxtNombre.grabFocus();
    }

    private void limpiarControles() {
        jtxtCodigo.setText("");
        jtxtNombre.setText("");
        jtxtPrecio.setText("");
        jtxtObservacion.setText("");
        jtxtBuscar.setText("");
        jtxtRuta.setText("");
        jlblFoto.setIcon(null);
        limpiarJTable();
    }

    public void reproducirSonido(String nombre) {
        try {
            String ruta = "src/sonidos/" + nombre + ".wav"; // Carpeta donde guardas tus audios
            File archivo = new File(ruta);
            if (!archivo.exists()) {
                System.err.println("No se encontró el archivo: " + ruta);
                return;
            }
            AudioInputStream audio = AudioSystem.getAudioInputStream(archivo);
            Clip clip = AudioSystem.getClip();
            clip.open(audio);
            clip.start();
        } catch (Exception e) {
            e.printStackTrace();
        }
    }

