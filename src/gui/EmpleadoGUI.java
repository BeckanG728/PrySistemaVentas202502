    private void jtxtBuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jtxtBuscarKeyReleased
        try {
            limpiarJTable();
            String nombre = jtxtBuscar.getText().strip();
            if (!nombre.isEmpty()) {
                rsEmpleado = objEmpleadoDAO.search(nombre);
                while (rsEmpleado.next()) {
                    Object[] registro = {
                        rsEmpleado.getInt(1),
                        rsEmpleado.getString(2),
                        rsEmpleado.getString(3),
                        rsEmpleado.getString(4),};
                    objDtm.addRow(registro);
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, e.getMessage() + " " + jtxtBuscar.getText());
        }
    }//GEN-LAST:event_jtxtBuscarKeyReleased

    private void jbtnGrabarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnGrabarActionPerformed
        try {
            String mensaje = "";

            String rutaMasculino = "C:\\fotosDemo\\masculino.jpg";
            String rutaFemenino = "C:\\fotosDemo\\femenino.png";

            EmpleadoTO objEmpleadoTO = new EmpleadoTO();
            objEmpleadoTO.setNombEmpl(jtxtNombre.getText().strip());
            objEmpleadoTO.setApatEmpl(jtxtApPaterno.getText().strip());
            objEmpleadoTO.setAmatEmpl(jtxtApMaterno.getText().strip());
            if (jrbtMasculino.isSelected()) {
                objEmpleadoTO.setSexoEmpl("M");
            } else {
                objEmpleadoTO.setSexoEmpl("F");
            }
            objEmpleadoTO.setDireEmpl(jtxtDireccion.getText().strip());
            obtenerIdDistrito();
            objEmpleadoTO.setIdDistrito(xidDistrito);
            objEmpleadoTO.setTelfEmpl(jtxtTelefono.getText().strip());
            objEmpleadoTO.setCeluEmpl(jtxtCelular.getText().strip());
            objEmpleadoTO.setEmailEmpl(jtxtEmail.getText().strip());
            objEmpleadoTO.setObsEmpl(jtxtObservacion.getText().strip());

            if (jtxtRuta.getText().isEmpty()) {
                if (jrbtMasculino.isSelected()) {
                    objEmpleadoTO.setFotoEmpl(rutaMasculino);
                }
                if (jrbtFemenino.isSelected()) {
                    objEmpleadoTO.setFotoEmpl(rutaFemenino);
                }
            } else {
                objEmpleadoTO.setFotoEmpl(jtxtRuta.getText());
            }

            if (sw) {
                objEmpleadoDAO.insert(objEmpleadoTO);
                mensaje = "Registro guardado";
            } else {
                objEmpleadoTO.setIdEmpleado(Integer.parseInt(jtxtCodigo.getText().strip()));
                objEmpleadoDAO.update(objEmpleadoTO);
                mensaje = "Registro actualizado";
            }
            reproducirSonido("guardado");
            habilitarControles(false);
            JOptionPane.showMessageDialog(rootPane, mensaje);
            limpiarControles();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, "Grabar:" + e.getMessage());
        }
    }//GEN-LAST:event_jbtnGrabarActionPerformed

    private void jbtnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnBorrarActionPerformed
        String codigo = jtxtCodigo.getText();
        if (codigo.isEmpty()) {
            return;
        }
        
        try {
            int opcion = JOptionPane.showConfirmDialog(rootPane, "Eliminar el registro?", "Eliminar", JOptionPane.YES_NO_OPTION);
            if (opcion == JOptionPane.YES_OPTION) {
                EmpleadoTO empleadoTO = new EmpleadoTO();
                empleadoTO.setIdEmpleado(Integer.parseInt(codigo));
                objEmpleadoDAO.delete(empleadoTO);
                limpiarControles();
                reproducirSonido("eliminado");
                JOptionPane.showMessageDialog(rootPane, "Registro borrado");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e);
        }

    }//GEN-LAST:event_jbtnBorrarActionPerformed

