    private void jtxtBuscarKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jtxtBuscarKeyReleased
        try {
            limpiarJTable();
            String nombre = jtxtBuscar.getText().strip();
            if (!nombre.isEmpty()) {
                rsProducto = objProductoDAO.search(nombre);
                while (rsProducto.next()) {
                    Object[] registro = {rsProducto.getInt(1), rsProducto.getString(2)};
                    objDtm.addRow(registro);
                }
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, e.getMessage() + " " + jtxtBuscar.getText());
        }
    }//GEN-LAST:event_jtxtBuscarKeyReleased

    private void jtblRegistrosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtblRegistrosMouseClicked

        try {
            xidProducto = Integer.parseInt(jtblRegistros.getValueAt(jtblRegistros.getSelectedRow(), 0).toString());

            try ( // Llamar a tu método DAO
                    ResultSet rsProd = objProductoDAO.searchID(xidProducto)) {
                if (rsProd.next()) {
                    jtxtCodigo.setText(String.valueOf(rsProd.getInt(1)));
                    jtxtNombre.setText(rsProd.getString(2));
                    jtxtPrecio.setText(String.format("%.2f", rsProd.getDouble(3)));
                    jtxtObservacion.setText(rsProd.getString(4));

                    // --- Carga segura de la imagen ---
                    Blob fotoBlob = rsProd.getBlob(5);
                    if (fotoBlob != null && fotoBlob.length() > 0) {
                        System.out.println("Imgena existe");
                        byte[] data = fotoBlob.getBytes(1, (int) fotoBlob.length());
                        BufferedImage foto = ImageIO.read(new ByteArrayInputStream(data));

                        if (foto != null) {
                            System.out.println("Imagen contruida");
                            ImageIcon imagen = new ImageIcon(foto);
                            Icon icon = new ImageIcon(imagen.getImage().getScaledInstance(
                                    jlblFoto.getWidth(),
                                    jlblFoto.getHeight(),
                                    Image.SCALE_SMOOTH
                            ));
                            jlblFoto.setIcon(icon);
                        } else {
                            jlblFoto.setIcon(null);
                        }
                    } else {
                        jlblFoto.setIcon(null);
                        System.out.println("⚠️ No hay imagen almacenada para este registro.");
                    }
                }
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error al cargar empleado: " + e.getMessage());
        }
    }//GEN-LAST:event_jtblRegistrosMouseClicked

    private void jbtnBorrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnBorrarActionPerformed
        try {
            if (jtxtCodigo.getText().isEmpty()) {
                JOptionPane.showMessageDialog(null, "Debe seleccionar un registro");
                return;
            }

            int op = JOptionPane.showConfirmDialog(rootPane, "¿Eliminar?", "PREGUNTA", JOptionPane.YES_NO_OPTION);

            if (op != JOptionPane.YES_OPTION) {
                return;
            }

            ProductoTO objProductoTO = new ProductoTO();
            objProductoTO.setIdProducto(Integer.parseInt(jtxtCodigo.getText()));
            objProductoDAO.delete(objProductoTO);
            reproducirSonido("eliminado");
            limpiarControles();
            JOptionPane.showMessageDialog(null, "Registro eliminado");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_jbtnBorrarActionPerformed

    private void jbtnSeleccionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnSeleccionarActionPerformed
        JFileChooser objJFileChooser = new JFileChooser();
        int op = objJFileChooser.showOpenDialog(this);
        if (op == objJFileChooser.APPROVE_OPTION) {
            ruta = objJFileChooser.getSelectedFile().getAbsolutePath();
            jlblFoto.setIcon(new ImageIcon(ruta));

            // Escalar la imagen al tamaño del JLabel
            ImageIcon iconoOriginal = new ImageIcon(ruta);
            Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(
                    jlblFoto.getWidth(),
                    jlblFoto.getHeight(),
                    Image.SCALE_SMOOTH
            );
            jlblFoto.setIcon(new ImageIcon(imagenEscalada));
            jtxtRuta.setText(ruta);
        }
    }//GEN-LAST:event_jbtnSeleccionarActionPerformed

